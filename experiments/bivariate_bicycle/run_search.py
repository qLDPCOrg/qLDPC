"""Brute-force search for bivariate bicycle codes with toric layouts.

This script enumerates the bivariate bicycle codes of arXiv:2308.07915 with generating polynomials

    A = 1 + x + x**ax * y**ay,
    B = 1 + y + x**bx * y**by,

where x and y generate cyclic groups of orders dim_x and dim_y, for a given torus width dim_x and
every height dim_y with --min-order <= dim_y <= dim_x.  The terms 1 + x and 1 + y give these codes
a manifestly toric layout on a dim_x-by-dim_y torus, in which each check acts on four neighboring
data qubits (as in the toric code) and two other data qubits.  Every bivariate bicycle code with a
toric layout and three terms per polynomial is equivalent to a code of this form; see
qldpc.codes.BBCode.get_equivalent_toric_layout_code_data.  Exponents (ax, ay, bx, by) that are
equivalent to others by symmetry, or that reduce a polynomial to a monomial, are skipped.  For every
remaining code with an encoding rate of at least --min-rate, the code distance is upper-bounded by
minimizing over --num-trials randomized trials.

Results are saved to a disk cache in the "cache" subdirectory of --results-dir (by default,
results/cache in this directory), keyed by (dims, exponents, num_trials), so an interrupted search
resumes where it left off.  Afterwards, collect_results.py exports the best codes found to a CSV
file in the same results directory.

Example:
    python experiments/bivariate_bicycle/run_search.py 12 --workers 8
"""

from __future__ import annotations

import argparse
import concurrent.futures
import functools
import itertools
import os
import pathlib
import traceback
from collections.abc import Callable, Iterable, Iterator

import diskcache
from sympy.abc import x, y

import qldpc
import qldpc.cache

RESULTS_DIR = pathlib.Path(__file__).parent / "results"  # default directory of all results
CACHE_NAME = "cache"  # subdirectory of the results directory that holds the search-results cache

# default search settings
MIN_ORDER = 3  # minimum cyclic group order
MIN_RATE = 1 / 36  # ignore codes with lower encoding rates
NUM_TRIALS = 1000  # for code distance calculations
NUM_WORKERS = max(1, (os.cpu_count() or 1) - 2)  # number of parallel jobs

####################################################################################################
# command-line interface


def main() -> None:
    """Search over bivariate bicycle codes in parallel, saving results to a disk cache."""
    args = parse_args()
    cache = qldpc.cache.get_disk_cache(CACHE_NAME, cache_dir=args.results_dir)
    jobs = (
        functools.partial(run_and_save, dims, exponents, args.min_rate, args.num_trials, cache)
        for dims, exponents in get_search_space(args.dim_x, args.min_order)
    )
    run_jobs(jobs, args.workers)


def parse_args() -> argparse.Namespace:
    """Parse and validate command-line arguments."""
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument("dim_x", type=int, help="order of the cyclic group generated by x")
    parser.add_argument(
        "--min-order",
        type=int,
        default=MIN_ORDER,
        help="minimum order of the cyclic group generated by y (default: %(default)s)",
    )
    parser.add_argument(
        "--min-rate",
        type=float,
        default=MIN_RATE,
        help="skip distance calculations for codes with lower encoding rates"
        " (default: %(default).6g)",
    )
    parser.add_argument(
        "--num-trials",
        type=int,
        default=NUM_TRIALS,
        help="number of randomized trials for upper-bounding code distances (default: %(default)s)",
    )
    parser.add_argument(
        "--workers",
        type=int,
        default=NUM_WORKERS,
        help="number of parallel jobs (default: %(default)s)",
    )
    add_results_dir_argument(parser)
    args = parser.parse_args()
    if args.min_order < 1:
        parser.error("--min-order must be positive")
    if args.dim_x < args.min_order:
        parser.error("dim_x must be at least --min-order")
    if args.min_rate <= 0:
        parser.error("--min-rate must be positive")
    if args.num_trials < 1:
        parser.error("--num-trials must be positive")
    if args.workers < 1:
        parser.error("--workers must be positive")
    return args


def add_results_dir_argument(parser: argparse.ArgumentParser) -> None:
    """Add the --results-dir option, which is shared by all bivariate bicycle code scripts."""
    parser.add_argument(
        "--results-dir",
        type=pathlib.Path,
        default=RESULTS_DIR,
        help="directory of the search-results cache and exported codes"
        " (default: the 'results' directory beside this script)",
    )


####################################################################################################
# code search


def get_search_space(
    dim_x: int, min_order: int
) -> Iterator[tuple[tuple[int, int], tuple[int, int, int, int]]]:
    """Iterate over the cyclic group orders and polynomial exponents of all codes in the search.

    Codes that are redundant_or_trivial are skipped.
    """
    for dim_y in range(min_order, dim_x + 1):
        dims = (dim_x, dim_y)
        for exponents in itertools.product(range(dim_x), range(dim_y), range(dim_x), range(dim_y)):
            if not redundant_or_trivial(dims, exponents):
                yield dims, exponents


def redundant_or_trivial(dims: tuple[int, int], exponents: tuple[int, int, int, int]) -> bool:
    """Is the given bivariate bicycle code equivalent to another in the search, or trivial?

    A code is skipped if one of the following symmetries yields lexicographically smaller data.
    Each symmetry maps a code to an equivalent code, up to multiplying a polynomial by a monomial
    and exchanging the roles of A and B:
    - exchanging x and y maps (dim_x, dim_y) to (dim_y, dim_x) and (ax, ay, bx, by) to
      (by, bx, ay, ax),
    - reflecting x -> x**-1 maps (ax, bx) to (1 - ax, -bx) modulo dim_x, and
    - reflecting y -> y**-1 maps (by, ay) to (1 - by, -ay) modulo dim_y.

    A code is also skipped if either of its polynomials reduces to a monomial over GF(2), as when
    A = 1 + x + 1 = x.
    """
    dim_x, dim_y = dims
    ax, ay, bx, by = exponents
    return (
        (dim_x, ax, ay) < (dim_y, by, bx)  # enforce torus width >= height
        or (ax, bx) > ((1 - ax) % dim_x, -bx % dim_x)  # reflection about x axis
        or (by, ay) > ((1 - by) % dim_y, -ay % dim_y)  # reflection about y axis
        or (ax, ay) in [(0, 0), (1, 0)]  # "trivial" polynomial
        or (bx, by) in [(0, 0), (0, 1)]  # "trivial" polynomial
    )


def run_and_save(
    dims: tuple[int, int],
    exponents: tuple[int, int, int, int],
    min_rate: float,
    num_trials: int,
    cache: diskcache.Cache,
    *,
    silent: bool = False,
) -> None:
    """Compute and cache the parameters of a bivariate bicycle code, unless they are already known.

    Args:
        dims: The orders (dim_x, dim_y) of the cyclic groups generated by x and y.
        exponents: The exponents (ax, ay, bx, by) in the generating polynomials of the code.
        min_rate: Skip the distance calculation if the encoding rate is below this cutoff.
        num_trials: The number of randomized trials for upper-bounding the code distance.
        cache: The cache in which to save code parameters, keyed by (dims, exponents, num_trials).
        silent: If True, do not print progress.
    """
    # report coarse progress by printing one line per polynomial A (namely, when B = 1 + y + x)
    if not silent and exponents[2:] == (1, 0):
        print(dims, exponents)

    key = (dims, exponents, num_trials)

    # check whether we already have data for this code
    if key in cache:
        nn, kk, dd = cache[key]
        # if we know the distance or the encoding rate is too low, there's nothing more to do
        if dd is not None or kk < nn * min_rate:
            return

    # compute and save code parameters
    params = get_bb_code_params(dims, exponents, min_rate, num_trials, silent=silent)
    cache[key] = params

    nn, kk, dd = params
    if not silent and dd is not None:
        merit = kk * dd**2 / nn
        print("", dims, exponents, (nn, kk, dd), f"{merit:.2f}")


def get_bb_code_params(
    dims: tuple[int, int],
    exponents: tuple[int, int, int, int],
    min_rate: float,
    num_trials: int,
    *,
    silent: bool = False,
) -> tuple[int, int, int | None]:
    """Construct a bivariate bicycle code and compute its parameters.

    Args:
        dims: The orders (dim_x, dim_y) of the cyclic groups generated by x and y.
        exponents: The exponents (ax, ay, bx, by) in the generating polynomials
            A = 1 + x + x**ax * y**ay and B = 1 + y + x**bx * y**by.
        min_rate: Skip the (expensive) distance calculation if the encoding rate is below this
            cutoff.
        num_trials: The number of randomized trials for upper-bounding the code distance.
        silent: If True, do not print progress.

    Returns:
        The number of physical qubits n, the number of logical qubits k, and an upper bound on the
        code distance d, or None in place of d if the encoding rate k / n is below min_rate.
    """
    ax, ay, bx, by = exponents
    poly_a = 1 + x + x**ax * y**ay
    poly_b = 1 + y + x**bx * y**by
    code = qldpc.codes.BBCode(dims, poly_a, poly_b)

    if code.dimension < code.num_qubits * min_rate:
        return code.num_qubits, code.dimension, None

    if not silent:
        print(" starting", dims, exponents)

    # min_rate > 0, so the code has k > 0 logical qubits and an integer distance bound
    distance = int(code.get_distance_bound(num_trials=num_trials))
    return code.num_qubits, code.dimension, distance


####################################################################################################
# helper functions


def run_jobs(jobs: Iterable[Callable[[], None]], num_workers: int) -> None:
    """Run picklable jobs in parallel processes, submitting a few at a time to bound memory use.

    Prints the traceback of every job that fails, and raises a RuntimeError at the end if any did.
    """
    max_pending_jobs = 4 * num_workers
    num_jobs = num_failures = 0
    pending: set[concurrent.futures.Future[None]] = set()
    with concurrent.futures.ProcessPoolExecutor(max_workers=num_workers) as executor:
        for job in jobs:
            while len(pending) >= max_pending_jobs:
                done, pending = concurrent.futures.wait(
                    pending, return_when=concurrent.futures.FIRST_COMPLETED
                )
                num_failures += sum(report_failure(future) for future in done)
            pending.add(executor.submit(job))
            num_jobs += 1
        remaining = concurrent.futures.as_completed(pending)
        num_failures += sum(report_failure(future) for future in remaining)
    if num_failures:
        raise RuntimeError(f"{num_failures} of {num_jobs} jobs failed")


def report_failure(future: concurrent.futures.Future[None]) -> bool:
    """Print the traceback of a finished job if it failed, and return whether it failed."""
    if (exception := future.exception()) is not None:
        traceback.print_exception(exception)
        return True
    return False


if __name__ == "__main__":
    main()

# balanced product codes


class BPCode(CSSCode):
    """Balanced product code.

    A balanced product code is a quotient of the hypergraph product code of two classical codes
    (see :class:`HGPCode`) by symmetries that the classical codes share.  This quotient has fewer
    qudits than the hypergraph product code, and with suitable classical codes and distance
    balancing (see :class:`DistanceBalancedCode`), it yields codes whose distance grows faster than
    the square root of their length (https://arxiv.org/abs/2012.09271).

    A symmetry of a classical code is a pair of permutations ``(p_checks, p_bits)`` of its checks
    and bits that leaves its parity check matrix ``H`` invariant, in the sense that
    ``H[p_checks][:, p_bits] == H``.  Here each permutation ``p`` is a sequence that lists the image
    ``p[j]`` of every index ``j``, or a SymPy permutation, which fixes the indices beyond its size.
    A symmetry can also be a single :class:`qldpc.abstract.GroupMember` that permutes the checks
    followed by the bits, such as ``GroupMember(p_checks) @ GroupMember(p_bits)``.  The group
    returned by :meth:`ClassicalCode.get_matrix_automorphism_group` consists of the symmetries of a
    classical code in this form.

    The qudits of the hypergraph product code are pairs of bits and pairs of checks of the two
    classical codes.  Its X-type checks are pairs of a check of the first code and a bit of the
    second, and its Z-type checks are pairs of a bit of the first code and a check of the second.
    The balanced product code identifies the qudits and checks of the hypergraph product code that
    are related by pairs of symmetries of the two classical codes (see
    :meth:`qldpc.objects.complexes.ChainComplex.balanced_product`).  Each qudit and check of the
    balanced product code is thereby an orbit of the group generated by these pairs.  If this group
    acts freely on the checks and bits of either classical code, each orbit has as many elements as
    the group, so that the balanced product code has fewer qudits and checks than the hypergraph
    product code by a factor of the group order.

    Without symmetries, a balanced product code is a hypergraph product code.  If the pairs of
    symmetries generate a group that acts freely on both classical codes, a balanced product code is
    a lifted product code (see :class:`LPCode`).  For example, if ``A`` and ``B`` are matrices over
    the group algebra of a cyclic group, their lifts ``A.lift()`` and ``B.lift()`` consist of blocks
    whose rows and columns are indexed by group members (see :meth:`qldpc.abstract.RingArray.lift`).
    Pairing a cyclic shift within every block of ``A.lift()`` with the inverse shift within every
    block of ``B.lift()`` then yields ``LPCode(A, B)``, up to the order of qudits and checks.

    The static method :meth:`from_seed` constructs balanced product codes from a single seed matrix
    with a symmetry, as in https://arxiv.org/abs/2505.13679, and :meth:`get_seed_symmetries` finds
    such symmetries with the optional ``pybliss`` package.  For example, the following constructs
    the ``[[12, 2, 3]]`` code in Example 1 of https://arxiv.org/abs/2505.13679 from the parity check
    matrix of a ring code, which is the incidence matrix of a cycle graph with six vertices, and has
    a symmetry of order 3:

    .. code-block:: python

        from qldpc import abstract, codes

        seed: codes.RingCode = codes.RingCode(6)
        symmetries: list[abstract.GroupMember] = codes.BPCode.get_seed_symmetries(seed, 3)
        code: codes.BPCode = codes.BPCode.from_seed(seed, symmetries[0])
        assert code.get_code_params() == (12, 2, 3)

    Similarly, the following constructs the ``[[360, 26, 5]]`` code in Example 2 of
    https://arxiv.org/abs/2505.13679 from the Lubotzky-Phillips-Sarnak expander graph ``X^{3,5}``,
    which is the Cayley graph of ``PGL(2, 5)`` generated by four matrices:

    .. code-block:: python

        import galois
        import networkx as nx
        import numpy as np
        import numpy.typing as npt
        from qldpc import abstract, codes
        from qldpc.objects import CayleyComplex

        field: type[galois.FieldArray] = galois.GF(5)
        generators: galois.FieldArray = field(
            [[[2, 2], [4, 3]], [[2, 4], [2, 3]], [[2, 3], [1, 3]], [[2, 1], [3, 3]]]
        )

        # a matrix g acts on 2 × 2 matrices by conjugation, which is unchanged by rescaling g, so
        # the action of g by conjugation represents g as a member of PGL(2, 5)
        group: abstract.Group = abstract.Group.from_generating_mats(
            *[np.kron(np.linalg.inv(generator).T, generator) for generator in generators]
        )
        graph: nx.Graph = CayleyComplex.build_cayley_graph(group.generators)
        incidence: npt.NDArray[np.int_] = nx.incidence_matrix(graph).toarray().astype(int)

        symmetries: list[abstract.GroupMember] = codes.BPCode.get_seed_symmetries(incidence, 5)
        code: codes.BPCode = codes.BPCode.from_seed(incidence, symmetries[0])
        assert code.get_code_params() == (360, 26, 5)

    Args:
        code_a: The first classical code.
        code_b: The second classical code.
        symmetries_a: Symmetries of the first code.
        symmetries_b: Symmetries of the second code, as many as there are symmetries of the first
            code.
        field: The finite field for the classical codes, if they are not ClassicalCode objects.

    References:

    - https://errorcorrectionzoo.org/c/balanced_product
    - https://arxiv.org/abs/2012.09271
    - https://arxiv.org/abs/2505.13679
    """

    code_a: ClassicalCode
    code_b: ClassicalCode
    chain: ChainComplex

    def __init__(
        self,
        code_a: ClassicalCode | npt.NDArray[np.int_] | Sequence[Sequence[int]],
        code_b: ClassicalCode | npt.NDArray[np.int_] | Sequence[Sequence[int]],
        symmetries_a: Sequence[abstract.GroupMember | tuple[Iterable[int], Iterable[int]]] = (),
        symmetries_b: Sequence[abstract.GroupMember | tuple[Iterable[int], Iterable[int]]] = (),
        field: int | type[galois.FieldArray] | None = None,
    ) -> None:
        self.code_a = ClassicalCode(code_a, field)
        self.code_b = ClassicalCode(code_b, field)
        # the transposed chain complex of code_b has bits in degree 0 and checks in degree 1, so its
        # symmetries permute bits before checks
        transposed_symmetries_b = []
        for index, symmetry in enumerate(symmetries_b):
            name = f"symmetries_b[{index}]"
            p_checks, p_bits = get_block_permutations(symmetry, self.code_b.matrix.shape, name)
            transposed_symmetries_b.append((p_bits, p_checks))
        self.chain = ChainComplex.balanced_product(
            ChainComplex([self.code_a.matrix]),
            ChainComplex([self.code_b.matrix]).T,
            symmetries_a,
            transposed_symmetries_b,
        )
        matrix_x, matrix_z = self.chain.op(1), self.chain.op(2).T
        assert not isinstance(matrix_x, abstract.RingArray)
        assert not isinstance(matrix_z, abstract.RingArray)
        super().__init__(matrix_x, matrix_z, is_subsystem_code=False)

    @staticmethod
    def from_seed(
        matrix: AbstractCode | IntegerArray | Sequence[Sequence[int]],
        symmetry: abstract.GroupMember | tuple[Iterable[int], Iterable[int]],
        field: int | type[galois.FieldArray] | None = None,
    ) -> BPCode:
        """Balanced product of a cycle graph with a seed matrix.

        Here ``symmetry`` is a symmetry of the seed matrix ``I``, which is either a pair
        ``(p_rows, p_cols)`` of permutations such that ``I[p_rows][:, p_cols] == I``, or a single
        GroupMember that permutes the rows followed by the columns of ``I`` (see :class:`BPCode`).
        Let ``l`` be the order of this symmetry, which is the least common multiple of the orders of
        ``p_rows`` and ``p_cols``.  This method constructs the balanced product of the parity check
        matrix of a length-``l`` cycle graph with the seed matrix, pairing a cyclic shift of the
        cycle graph with the symmetry of the seed matrix.  The cyclic shift generates a group of
        order ``l`` that acts freely on the cycle graph.  The resulting code therefore has one qudit
        for every row and every column of the seed matrix, whereas the hypergraph product code has
        ``l`` times as many.

        Over GF(2), the result is the code of Eq. (3) in Definition 1 of
        https://arxiv.org/abs/2505.13679, up to a permutation of qudits, with the permutation
        matrices ``R`` and ``C`` of that work given by ``R = GroupMember(p_rows).to_matrix()`` and
        ``C = GroupMember(p_cols).to_matrix().T`` (see
        :meth:`qldpc.abstract.GroupMember.to_matrix`).  That work states Definition 1 for symmetries
        whose orbits all have length ``l``, but this method accepts any symmetry.  If ``symmetry``
        is a GroupMember, then ``symmetry.to_matrix()`` is the block-diagonal matrix with blocks
        ``R`` and ``C.T``.  Symmetries of a seed matrix can be found with
        :meth:`get_seed_symmetries`.

        Args:
            matrix: The seed matrix, or a classical code with the seed matrix as its parity check
                matrix.
            symmetry: A symmetry of the seed matrix.
            field: The finite field of the seed matrix, if it is not a ``galois.FieldArray`` or a
                code.
        """
        seed = ClassicalCode(matrix, field)
        # validate the symmetry before using its orders
        p_rows, p_cols = get_block_permutations(symmetry, seed.matrix.shape, "symmetry")
        if not np.array_equal(seed.matrix[p_rows][:, p_cols], seed.matrix):
            raise ValueError("symmetry is not a symmetry of the seed matrix")
        member_rows, member_cols = abstract.GroupMember(p_rows), abstract.GroupMember(p_cols)
        length = math.lcm(int(member_rows.order()), int(member_cols.order()))
        shift = [length - 1, *range(length - 1)]
        return BPCode(RingCode(length, seed.field), seed, [(shift, shift)], [(p_rows, p_cols)])

    @staticmethod
    def get_seed_symmetries(
        matrix: AbstractCode | IntegerArray | Sequence[Sequence[int]],
        order: int,
        field: int | type[galois.FieldArray] | None = None,
    ) -> list[abstract.GroupMember]:
        """Find symmetries of a seed matrix for :meth:`from_seed`.

        This method finds the automorphisms of order ``order`` of the seed matrix (see
        :meth:`ClassicalCode.get_matrix_automorphism_group`), and returns one automorphism in each
        conjugacy class.  Each automorphism is a GroupMember that permutes the rows followed by the
        columns of the seed matrix.  Conjugate automorphisms ``g`` and ``h * g * h**-1`` yield equal
        codes, up to a permutation of qudits, because the automorphism ``h`` relabels the rows and
        columns of the seed matrix without changing it.  This method enumerates the automorphism
        group of the seed matrix, which can take a long time if the group is large.  Computing
        automorphisms requires the optional ``pybliss`` package, which can be installed with
        ``pip install 'qldpc[bliss]'``.

        Args:
            matrix: The seed matrix, or a classical code with the seed matrix as its parity check
                matrix.
            order: The order of the symmetries to find.
            field: The finite field of the seed matrix, if it is not a ``galois.FieldArray`` or a
                code.
        """
        group = ClassicalCode(matrix, field).get_matrix_automorphism_group()
        return [
            abstract.GroupMember.from_sympy(min(conjugacy_class, key=lambda perm: perm.array_form))
            for conjugacy_class in group.to_sympy().conjugacy_classes()
            if next(iter(conjugacy_class)).order() == order
        ]

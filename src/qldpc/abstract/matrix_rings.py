"""Module for abstract algebra: matrix rings over a finite field.

.. warning::
    This module does not promise to be performant.  If you need to do heavy numerical abstract
    algebra, you're probably better served by GAP or MAGMA (or maybe SageMath).
"""

from __future__ import annotations

import collections
import functools
from collections.abc import Hashable
from typing import Any

import galois
import numpy as np
import numpy.typing as npt

from .rings import Ring, RingMember

####################################################################################################
# matrix rings


class MatrixRing(Ring):
    """A ring of square matrices over a finite field, generated by given matrices.

    The members of this ring are all linear combinations of the identity matrix and of products of
    the given generating matrices.  There must be at least one generator, and all generators must be
    nonempty square matrices of the same size.

    The ``field`` argument sets the base field.  If it is omitted, the base field is that of the
    first generator if it is a galois field array, and ``GF(2)`` otherwise.  Generators that are
    field arrays over another field raise a ValueError.

    A ring member lifts to the matrix that it represents, so ``lift_dim`` is the size of the
    matrices.  The dimension of the ring as a vector space over its field is ``dim``.  The member
    that a matrix represents is ``MatrixRing.member_from_matrix(matrix)``.

    The basis starts with the identity matrix.  Products of generators follow in breadth-first
    order, which appends generators on the right.  A product joins the basis only if it is linearly
    independent of the earlier basis elements.  The label of a basis element is its position in the
    basis.  Two rings are equal if they have the same field and basis.

    ``RingMember.T`` is the matrix transpose, so ``has_involution`` is True exactly when the ring is
    closed under transposition.  A ring generated by permutation matrices is closed under
    transposition, because the transpose of a permutation matrix is its inverse, which is a power of
    the matrix.

    Example:
        .. code-block:: python

            import numpy as np
            from qldpc.abstract import MatrixRing

            shift = np.roll(np.eye(3, dtype=int), 1, axis=0)
            ring = MatrixRing(shift)  # isomorphic to the algebra of a cyclic group of order 3
            assert ring.dim == ring.lift_dim == 3
            x = ring.generators[0]
            assert x**3 == ring.one and ring.has_involution and ring.is_commutative
            assert ring.member_from_matrix(shift @ shift) == x**2
    """

    _basis_lifts: galois.FieldArray  # basis matrices, with shape (dim, lift_dim, lift_dim)
    _structure_constants: galois.FieldArray  # coefficients of products of basis matrices
    _pivot_columns: list[int]  # columns of flattened basis matrices that determine coefficients
    _pivot_inverse: galois.FieldArray  # inverse of the basis matrices restricted to those columns
    # generating matrices, with shape (number of generators, lift_dim, lift_dim)
    _generator_lifts: galois.FieldArray

    def __init__(
        self,
        *generators: npt.ArrayLike,
        field: int | type[galois.FieldArray] | None = None,
    ) -> None:
        # check that there are generators, and identify the base field
        if not generators:
            raise ValueError("A MatrixRing requires at least one generating matrix")
        if field is None and isinstance(generators[0], galois.FieldArray):
            field = type(generators[0])
        super().__init__(field)

        # validate and store the generators
        matrices = [self._to_field(generator) for generator in generators]
        shape = matrices[0].shape
        if (
            len(shape) != 2
            or shape[0] != shape[1]
            or shape[0] == 0
            or any(matrix.shape != shape for matrix in matrices)
        ):
            raise ValueError(
                "The generators of a MatrixRing must be nonempty square matrices of one size"
            )
        self._generator_lifts = self.field(matrices)

        # find the basis of the ring, and pivot columns of the flattened basis matrices.  The basis
        # matrices restricted to the pivot columns form an invertible square matrix, so the entries
        # of a matrix at the pivot columns determine its coefficients, if the matrix is in the span
        # of the basis.
        self._basis_lifts, self._pivot_columns = _get_product_basis(matrices)
        self._basis_lifts.flags.writeable = False
        flat_basis = self._basis_lifts.reshape(self.dim, -1).view(self.field)
        self._pivot_inverse = np.linalg.inv(flat_basis[:, self._pivot_columns]).view(self.field)

        # find the products of pairs of basis elements, which turn products of members into tensor
        # contractions
        self._structure_constants = self._get_structure_constants()
        self._structure_constants.flags.writeable = False

    @property
    def dim(self) -> int:
        """Dimension of this ring as a vector space over its base field."""
        return len(self._basis_lifts)

    @property
    def lift_dim(self) -> int:
        """Size of the matrices in this ring."""
        return self._basis_lifts.shape[-1]

    @property
    def name(self) -> str:
        """A name for this ring, which is not required to uniquely identify the ring."""
        return (
            f"Algebra of dimension {self.dim} spanned by {self.lift_dim}x{self.lift_dim} matrices"
            f" over GF({self.field.order})"
        )

    def __eq__(self, other: object) -> bool:
        # rings are equal if they have the same basis, so that members have the same coordinates.
        # Comparing a ring with itself is common, and comparing bases can be costly.
        return other is self or (
            isinstance(other, MatrixRing)
            and self.field is other.field
            and np.array_equal(self._basis_lifts, other._basis_lifts)
        )

    def __hash__(self) -> int:
        return hash((self.field.order, self._basis_lifts.tobytes()))

    @functools.cached_property
    def is_commutative(self) -> bool:
        """Is this ring commutative?"""
        matrices = self._generator_lifts
        return all(np.array_equal(aa @ bb, bb @ aa) for aa in matrices for bb in matrices)

    @property
    def has_involution(self) -> bool:
        """Is this ring closed under matrix transposition, which is ``RingMember.T``?"""
        return self._transpose_coefficient_map is not None

    @property
    def one(self) -> RingMember:
        """One (multiplicative identity) element."""
        return RingMember(self, (1, 0))

    @property
    def generators(self) -> list[RingMember]:
        """The generating matrices of this ring, as ring members."""
        return [self.member_from_matrix(matrix) for matrix in self._generator_lifts]

    def member_from_matrix(self, matrix: npt.ArrayLike) -> RingMember:
        """The member of this ring that lifts to a given matrix.

        Raise a ValueError if the matrix is not in this ring, has the wrong size, or is over another
        field.
        """
        matrices = self._to_field(matrix)[np.newaxis]
        if matrices.shape[1:] != self._basis_lifts.shape[1:]:
            raise ValueError(
                f"A member of {self} lifts to a {self.lift_dim}x{self.lift_dim} matrix, but the"
                f" matrix has shape {matrices.shape[1:]}"
            )
        coefficients = self._get_coefficients_in_ring(matrices)
        if coefficients is None:
            raise ValueError("The matrix is not in the ring")
        return RingMember.from_vector(coefficients[0], self)

    def lift(self, label: Any, /, *, right: bool = False) -> galois.FieldArray:
        """Lift the basis element with a given label to the matrix that it represents.

        If ``right=True``, lift to the transpose of that matrix, which is an anti-representation.
        For the matrix of multiplication from the right on coefficient vectors, see
        ``regular_lift(label, right=True)``.  The matrix is read-only.
        """
        matrix = self._basis_lifts[self._as_label(label)]
        return matrix.T if right else matrix

    def regular_lift(self, label: Any, /, *, right: bool = False) -> galois.FieldArray:
        """Lift the basis element with a given label to its regular representation.

        See ``Ring.regular_lift``.  The matrix is read-only.
        """
        # the matrix of multiplication by e_a from the left has entries [c, b] = constants[a, b, c],
        # and that of multiplication by e_b from the right has entries [c, a] = constants[a, b, c],
        # where constants are the structure constants (see _get_structure_constants)
        axes = (1, 2, 0) if right else (0, 2, 1)
        return self._structure_constants.transpose(*axes)[self._as_label(label)]

    @functools.cached_property
    def _labels(self) -> list[Hashable]:
        return list(range(self.dim))

    def _index(self, label: Any) -> int:
        return self._as_label(label)

    def _as_label(self, label: Any) -> int:
        if not (isinstance(label, (int, np.integer)) and 0 <= label < self.dim):
            raise ValueError(f"Invalid basis label {label!r} for a ring of dimension {self.dim}")
        return int(label)

    def _multiply(self, left: RingMember, right: RingMember) -> RingMember:
        # row b of left_times_basis holds the coefficients of left * e_b, which are the sum over a
        # of left_a * _structure_constants[a, b, :]
        flat_constants = self._structure_constants.reshape(self.dim, -1)
        left_times_basis = (
            (left.to_vector() @ flat_constants).view(self.field).reshape(self.dim, -1)
        )
        product = right.to_vector() @ left_times_basis
        return RingMember.from_vector(product.view(self.field), self)

    def _apply_involution(self, member: RingMember) -> RingMember:
        if self._transpose_coefficient_map is None:
            raise ValueError(
                f"{self} is not closed under matrix transposition, so it has no involution for"
                " RingMember.T"
            )
        transposed = member.to_vector() @ self._transpose_coefficient_map
        return RingMember.from_vector(transposed.view(self.field), self)

    @functools.cached_property
    def _transpose_coefficient_map(self) -> galois.FieldArray | None:
        """Matrix that maps the coefficients of a member to those of its transpose, or None.

        Row ``a`` holds the coefficients of the transpose of basis matrix ``a``.  There is no such
        matrix if the transpose of any basis matrix is not in the ring.
        """
        transposes = self._basis_lifts.transpose(0, 2, 1).view(self.field)
        return self._get_coefficients_in_ring(transposes)

    def _get_coefficients_in_ring(self, matrices: galois.FieldArray) -> galois.FieldArray | None:
        """Coefficients of each matrix in a stack of matrices, or None if any is not in the ring."""
        coefficients = self._get_coefficients(matrices)
        flat_matrices = matrices.reshape(len(matrices), -1)
        in_ring = np.array_equal(
            coefficients @ self._basis_lifts.reshape(self.dim, -1), flat_matrices
        )
        return coefficients if in_ring else None

    def _get_coefficients(self, matrices: galois.FieldArray) -> galois.FieldArray:
        """Coefficients of each matrix in a stack of matrices, in the basis of this ring.

        The coefficients are correct only for matrices in the span of the basis.
        """
        flat_matrices = matrices.reshape(-1, self.lift_dim**2)
        return (flat_matrices[:, self._pivot_columns] @ self._pivot_inverse).view(self.field)

    def _get_structure_constants(self) -> galois.FieldArray:
        """Coefficients of the products of pairs of basis matrices, indexed as ``[a, b, c]``.

        The entry ``[a, b, c]`` is the coefficient of ``e_c`` in ``e_a * e_b``, where ``e_a`` is
        basis matrix ``a``.
        """
        # multiply each basis matrix by all basis matrices at once
        constants = self.field.Zeros((self.dim, self.dim, self.dim))
        for index, matrix in enumerate(self._basis_lifts):
            constants[index] = self._get_coefficients((matrix @ self._basis_lifts).view(self.field))
        return constants

    def _to_field(self, matrix: npt.ArrayLike) -> galois.FieldArray:
        """Convert a matrix to an array over the field of this ring.

        Raise a ValueError for a field array over another field.
        """
        if isinstance(matrix, galois.FieldArray) and type(matrix) is not self.field:
            raise ValueError(f"The matrices of a MatrixRing must be over GF({self.field.order})")
        return self.field(np.asarray(matrix))


def _get_product_basis(generators: list[galois.FieldArray]) -> tuple[galois.FieldArray, list[int]]:
    """A basis for the span of the identity and all products of the given generating matrices.

    The basis is built from the identity and then products of generators, in the order in which
    breadth-first search finds linearly independent products.

    Returns:
        The basis matrices, and the indices of the columns of the flattened basis matrices on which
        the basis forms an invertible square matrix.
    """
    # search for products of generators, starting from the identity
    field = type(generators[0])
    size = generators[0].shape[0]
    candidates = collections.deque([field.Identity(size)])
    basis: list[galois.FieldArray] = []
    # flattened basis, row-reduced so that each row has a 1 at its pivot and 0 at other pivots
    echelon = field.Zeros((0, size**2))
    pivots: list[int] = []
    while candidates:
        matrix = candidates.popleft()

        # skip a product that is in the span of the basis found so far
        residual = matrix.reshape(-1) - (matrix.reshape(-1)[pivots] @ echelon).view(field)
        if not residual.any():
            continue

        # add the product to the basis, and to the row-reduced flattened basis
        pivot = int(np.flatnonzero(residual)[0])
        residual = residual / residual[pivot]
        echelon = (echelon - echelon[:, [pivot]] @ residual[np.newaxis, :]).view(field)
        echelon = np.vstack([echelon, residual]).view(field)
        pivots.append(pivot)
        basis.append(matrix)

        # queue the products of the new basis matrix with generators
        candidates.extend((matrix @ generator).view(field) for generator in generators)
    return field(np.array(basis)), pivots

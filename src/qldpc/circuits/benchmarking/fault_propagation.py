# bounded fault propagation certification


def certify_bounded_fault_propagation(
    circuit: stim.Circuit,
    *,
    output_qubits: Sequence[int] | None = None,
    css_weight: bool | None = None,
    max_weight: int | None = None,
    add_flags: bool = False,
    post_select: bool | Collection[int] | Literal["flags"] = False,
) -> BoundedFaultPropagationCertificate:
    """Certify bounded fault propagation in a noisy Clifford state-preparation circuit.

    An error mechanism is one error instruction of the circuit's detector error model (DEM), and a
    fault is a set of error mechanisms, represented by a binary vector.  The fault weight is the
    number of error mechanisms in a fault, and a primitive fault is a fault of fault weight one.
    The Pauli weight of an error on the output qubits is either its physical weight (the number of
    qubits that it acts on), or its CSS weight ``max(|x|, |z|)``, where ``x`` and ``z`` are the X
    and Z parts of the error.

    Fault propagation is bounded if every fault that passes post-selection satisfies the bound: the
    error that it leaves on the output state is equivalent to an error whose Pauli weight is at most
    the fault weight.  Two errors are equivalent if they differ by a stabilizer of the prepared
    state.  Bounded fault propagation is a sufficient criterion for fault-tolerant state
    preparation; see Definition 3 in Section 4.2 of
    `arXiv:0904.2557 <https://arxiv.org/abs/0904.2557>`_.

    Without post-selection, it suffices to check that each primitive fault alone leaves an error
    equivalent to one of Pauli weight at most one, because error propagation through a Clifford
    circuit is linear and Pauli weight is subadditive.  With post-selection, primitive faults that
    each fire a detector can pass together, so the search also considers the faults that pass and
    contain no other nonempty fault that passes.  The proof that this is enough is in
    ``fault_propagation.md`` beside this module.

    Args:
        circuit: Noisy Stim Clifford circuit starting in Stim's all-zero state.

    Keyword args:
        output_qubits: Distinct indices of the output qubits, at least one, in the order that the
            certificate uses for Pauli strings.  Default: all qubits that the circuit acts on and
            never measures.
        css_weight: True to choose CSS weight as the Pauli weight, or False to choose physical
            weight.  Default: CSS weight if the prepared state is a CSS state in the physical Pauli
            basis (meaning its stabilizer group is generated by pure-X and pure-Z operators), and
            physical weight otherwise.  A CSS code can prepare a non-CSS state, such as a logical Y
            eigenstate; pass ``css_weight=True`` for such a state if CSS weight is appropriate.
        max_weight: The largest fault weight to certify, a positive integer.  Default: None, for no
            limit.  It does not change the result without post-selection.  With post-selection, the
            search time can grow exponentially with the fault weight, so a limit bounds it.
        add_flags: Whether to add a flag detector for each measurement that no detector or
            observable addresses, as in ``get_state_prep_diagnostic_circuit``.  Default: False.
        post_select: The detectors to post-select on, among the circuit's detectors followed by any
            added flag detectors.  True selects all of them, False selects none, a collection of
            distinct integers selects the detectors with those indices (negative indices count back
            from the last detector), and "flags" selects exactly the added flag detectors, which
            requires ``add_flags=True``.  A fault passes post-selection if none of the selected
            detectors fire, where a detector fires if an odd number of the fault's error mechanisms
            flip it.  Default: False.

    Returns:
        A certificate of bounded fault propagation, which includes a counterexample if applicable.

    Raises:
        ValueError: If ``css_weight``, ``output_qubits``, ``max_weight``, or ``post_select`` has an
            invalid type or value, if the output qubits do not end in one definite stabilizer state,
            or if Stim cannot convert the circuit to a DEM.
    """
    if css_weight is not None and not isinstance(css_weight, bool):
        raise ValueError("css_weight must be a bool or None")
    if max_weight is not None:
        if not _is_integer(max_weight) or max_weight < 1:
            raise ValueError("max_weight must be a positive integer or None")
        max_weight = int(max_weight)
    if output_qubits is None:
        output_qubits = _get_unmeasured_qubits(circuit)
        if not output_qubits:
            raise ValueError("The circuit has no unmeasured qubits to use as output_qubits")
    try:
        qubits = tuple(output_qubits)
    except TypeError as error:
        raise ValueError("output_qubits must be a sequence of qubit indices") from error
    _validate_output_qubits(qubits, circuit.num_qubits)

    # Flag detectors come after the detectors that the circuit already has.
    detector_record = DetectorRecord({"prep": range(circuit.num_detectors)})
    flag_detectors = stim.Circuit()
    if add_flags:
        for measurement in get_unaddressed_measurements(circuit):
            target = stim.target_rec(measurement - circuit.num_measurements)
            flag_detectors.append("DETECTOR", [target])
    detector_record.append({"flags": range(flag_detectors.num_detectors)})
    selected = _get_post_selection_detectors(post_select, detector_record, add_flags)
    circuit = circuit + flag_detectors

    stabilizers = get_state_stabilizers(circuit, qubits)
    if len(stabilizers) != len(qubits):
        raise ValueError("Selected outputs must have a definite pure, complete stabilizer state")
    matrix = np.array([math.string_to_op(stabilizer) for stabilizer in stabilizers], dtype=np.uint8)
    resolved_css_weight = _is_css_state(matrix) if css_weight is None else css_weight
    dem, flags, syndromes = _get_primitive_fault_maps(circuit, stabilizers, qubits, selected)
    counterexample, _ = _certify_maps(flags, syndromes, matrix, resolved_css_weight, max_weight)
    return BoundedFaultPropagationCertificate(
        tuple(map(int, qubits)),
        tuple(stabilizers),
        dem,
        counterexample,
        resolved_css_weight,
        max_weight,
        selected,
    )


@dataclass(frozen=True)
class BoundedFaultPropagationCertificate:
    """The result of certifying bounded fault propagation in a state-preparation circuit.

    Equivalence, fault weight, Pauli weight, and bounded fault propagation are as defined in
    ``certify_bounded_fault_propagation``.

    Attributes:
        output_qubits: The output qubit indices.  The ``i``-th Pauli of every Pauli string in this
            certificate acts on qubit ``output_qubits[i]``.
        target_stabilizers: Stim Pauli strings that generate the stabilizer group of the prepared
            state, one per output qubit.
        detector_error_model: The circuit's detector error model, flattened and undecomposed.  Its
            detectors are the circuit's own, then any added flag detectors, then one for each target
            stabilizer, in order.
        counterexample: The counterexample if ``certified`` is False, and None otherwise.
        css_weight: Whether the certificate chose CSS weight (True) or physical weight (False) as
            the Pauli weight.
        max_weight: The largest fault weight that the certificate covers, or None for no limit.
        post_selection_detectors: The post-selection detectors, as indices among the detectors of
            ``detector_error_model``.
    """

    output_qubits: tuple[int, ...]
    target_stabilizers: tuple[stim.PauliString, ...]
    detector_error_model: stim.DetectorErrorModel
    counterexample: BoundedFaultPropagationCounterexample | None
    css_weight: bool
    max_weight: int | None
    post_selection_detectors: tuple[int, ...]

    @property
    def certified(self) -> bool:
        """Whether fault propagation is bounded, within the limit ``max_weight``."""
        return self.counterexample is None


@dataclass(frozen=True)
class BoundedFaultPropagationCounterexample:
    """A fault that passes post-selection and violates the bound.

    The error that the fault leaves on the output, its output error, has no equivalent error whose
    Pauli weight is at most the fault weight.  No fault that passes post-selection and has a smaller
    fault weight violates the bound.  Equivalence, fault weight, Pauli weight, and the bound are as
    defined in ``certify_bounded_fault_propagation``.

    Attributes:
        fault_indices: The indices, among the error instructions of the certificate's
            ``detector_error_model``, of the primitive faults that make up the fault, in increasing
            order.
        output_syndrome: The syndrome of the fault's output error: entry ``j`` is 1 if the error
            anticommutes with ``target_stabilizers[j]``.
        output_weight_lower_bound: A lower bound on the Pauli weight of every error equivalent to
            the output error; it exceeds ``fault_weight``.
        output_pauli: A Pauli error with this syndrome, on the output qubits in the order of the
            certificate's ``output_qubits``.  It is equivalent to the output error, but need not be
            that error or one of the smallest Pauli weight.
    """

    fault_indices: tuple[int, ...]
    output_syndrome: tuple[int, ...]
    output_weight_lower_bound: int
    output_pauli: stim.PauliString

    @property
    def fault_weight(self) -> int:
        """The fault weight of this counterexample's fault."""
        return len(self.fault_indices)



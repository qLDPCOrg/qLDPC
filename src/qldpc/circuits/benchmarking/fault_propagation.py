# helper methods


def _get_fault_maps(
    circuit: stim.Circuit, stabilizers: Sequence[stim.PauliString], qubits: Sequence[int]
) -> tuple[stim.DetectorErrorModel, list[int]]:
    """Get the certificate's detector error model and the output syndrome of each fault.

    A syndrome is an integer with bit ``j`` for stabilizer ``j``, and the syndromes follow the order
    of the DEM's error instructions.
    """
    diagnostics = get_pauli_product_measurements(stabilizers, qubits=qubits)
    for jj in range(len(stabilizers)):
        diagnostics.append("DETECTOR", [stim.target_rec(jj - len(stabilizers))])
    diagnostic_circuit = circuit + diagnostics

    # Converting the noiseless circuit raises an error for a nondeterministic detector or
    # observable.
    diagnostic_circuit.without_noise().detector_error_model()

    # Stim needs this flag for correlated error chains.  It treats their components as independent
    # faults, which only approximates their probabilities, and no probabilities are used here.
    dem = diagnostic_circuit.detector_error_model(approximate_disjoint_errors=True).flattened()

    syndromes: list[int] = []
    for instruction in dem:
        if instruction.type != "error":
            continue
        # Detector ``circuit.num_detectors + j`` measures stabilizer ``j``.
        syndrome = 0
        for target in instruction.targets_copy():
            if target.is_relative_detector_id() and target.val >= circuit.num_detectors:
                syndrome ^= 1 << (target.val - circuit.num_detectors)
        syndromes.append(syndrome)
    return dem, syndromes


def _get_unmeasured_qubits(circuit: stim.Circuit) -> tuple[int, ...]:
    """Qubits that some instruction acts on and no measurement targets, in increasing order."""
    touched: set[int] = set()
    measured: set[int] = set()
    for instruction in circuit.flattened():
        name = instruction.name
        # The targets of MPAD are padding bits, not qubits.
        if name in ("DETECTOR", "OBSERVABLE_INCLUDE", "QUBIT_COORDS", "MPAD"):
            continue
        qubits = {tt.qubit_value for tt in instruction.targets_copy() if tt.qubit_value is not None}
        touched |= qubits
        # Heralded noise reports whether a fault occurred, and it does not measure the qubit.
        if stim.gate_data(name).produces_measurements and not name.startswith("HERALDED_"):
            measured |= qubits
    return tuple(sorted(touched - measured))


def _is_css_state(stabilizers: npt.NDArray[np.uint8]) -> bool:
    """Test whether a complete rank-n stabilizer space is CSS in the physical basis."""
    n = len(stabilizers)
    # Let W be the stabilizer space, and W_X and W_Z the X and Z parts of its rows.  The pure-X and
    # pure-Z elements of W have dimensions n-rank(W_Z) and n-rank(W_X) and meet only in 0, so they
    # span W exactly when rank(W_X)+rank(W_Z)=n, whatever generators are used.
    ranks = [
        np.linalg.matrix_rank(galois.GF2(sector))
        for sector in (stabilizers[:, :n], stabilizers[:, n:])
    ]
    return sum(ranks) == n


def _validate_output_qubits(qubits: tuple[int, ...], num_qubits: int) -> None:
    if (
        not qubits
        or any(isinstance(jj, bool) or not isinstance(jj, numbers.Integral) for jj in qubits)
        or any(not 0 <= jj < num_qubits for jj in qubits)
        or len(set(qubits)) != len(qubits)
    ):
        raise ValueError("output_qubits must contain distinct in-range integer indices")


def _certify_maps(
    syndromes: Sequence[int], stabilizers: npt.ArrayLike, css_weight: bool
) -> BoundedFaultPropagationCounterexample | None:
    """Find the first fault whose error is not equivalent to an error of weight at most one."""
    oracle = PauliCosetSearch(stabilizers, metric="css" if css_weight else "pauli")

    # Faults with equal syndromes leave equivalent errors, so each syndrome is checked once.
    first_fault: dict[int, int] = {}
    for index, syndrome in enumerate(syndromes):
        first_fault.setdefault(syndrome, index)
    for syndrome, index in first_fault.items():
        bound = oracle.get_min_weight_bound(syndrome, 1)
        if not bound.within_max_weight:
            return _get_counterexample(index, syndrome, bound, oracle.num_qubits)
    return None


def _get_counterexample(
    index: int, syndrome: int, bound: MinWeightBound, num_qubits: int
) -> BoundedFaultPropagationCounterexample:
    """Describe a violating fault by its DEM index and an error on the output qubits."""
    n = num_qubits
    pauli = math.op_to_string(np.array([(bound.representative >> jj) & 1 for jj in range(2 * n)]))
    return BoundedFaultPropagationCounterexample(
        (index,),
        tuple((syndrome >> jj) & 1 for jj in range(n)),
        bound.lower_bound,
        str(pauli),
    )

# helper methods


def _get_fault_maps(
    circuit: stim.Circuit,
    stabilizers: Sequence[stim.PauliString],
    qubits: Sequence[int],
    selected: Sequence[int],
) -> tuple[stim.DetectorErrorModel, list[int], list[int]]:
    """Get the certificate's detector error model, and the flags and syndrome of each fault.

    The flags of a fault have bit ``j`` for the ``j``-th selected detector, and its syndrome has bit
    ``j`` for stabilizer ``j``.  Both lists follow the order of the DEM's error instructions.
    """
    diagnostics = get_pauli_product_measurements(stabilizers, qubits=qubits)
    for jj in range(len(stabilizers)):
        diagnostics.append("DETECTOR", [stim.target_rec(jj - len(stabilizers))])
    diagnostic_circuit = circuit + diagnostics

    # Stim raises an error here for a nondeterministic detector or observable.
    diagnostic_circuit.without_noise().detector_error_model()

    # Stim needs this flag for correlated error chains.  It treats their components as independent
    # faults, which only approximates their probabilities, and no probabilities are used here.
    dem = diagnostic_circuit.detector_error_model(approximate_disjoint_errors=True).flattened()

    selected_position = {detector: jj for jj, detector in enumerate(selected)}
    flags: list[int] = []
    syndromes: list[int] = []
    for instruction in dem:
        if instruction.type != "error":
            continue
        # Detector ``circuit.num_detectors + j`` measures stabilizer ``j``.
        flag = syndrome = 0
        for target in instruction.targets_copy():
            if not target.is_relative_detector_id():
                continue
            if target.val in selected_position:
                flag ^= 1 << selected_position[target.val]
            if target.val >= circuit.num_detectors:
                syndrome ^= 1 << (target.val - circuit.num_detectors)
        flags.append(flag)
        syndromes.append(syndrome)
    return dem, flags, syndromes


def _get_unmeasured_qubits(circuit: stim.Circuit) -> tuple[int, ...]:
    """Qubits that some instruction acts on and no measurement targets, in increasing order."""
    touched: set[int] = set()
    measured: set[int] = set()
    for instruction in circuit.flattened():
        name = instruction.name
        # The targets of MPAD are padding bits, not qubits.
        if name in ("DETECTOR", "OBSERVABLE_INCLUDE", "QUBIT_COORDS", "MPAD"):
            continue
        qubits = {tt.qubit_value for tt in instruction.targets_copy() if tt.qubit_value is not None}
        touched |= qubits
        # Heralded noise reports whether a fault occurred, and it does not measure the qubit.
        if stim.gate_data(name).produces_measurements and not name.startswith("HERALDED_"):
            measured |= qubits
    return tuple(sorted(touched - measured))


def _get_post_selection_detectors(
    post_select: bool | Collection[int] | Literal["flags"],
    detector_record: DetectorRecord,
    add_flags: bool,
) -> tuple[int, ...]:
    """Get the distinct indices of the detectors to post-select on."""
    invalid = 'post_select must be a bool, "flags", or a collection of detector indices'
    if isinstance(post_select, str):
        if post_select != "flags":
            raise ValueError(invalid)
        if not add_flags:
            raise ValueError('post_select="flags" requires add_flags=True')
    elif not isinstance(post_select, bool):
        try:
            post_select = tuple(post_select)
        except TypeError as error:
            raise ValueError(invalid) from error
        if not all(_is_integer(jj) for jj in post_select):
            raise ValueError("post_select must contain integer detector indices")
    selected = tuple(int(jj) for jj in _get_selected_detectors(post_select, detector_record))
    if len(set(selected)) != len(selected):
        raise ValueError("post_select must not repeat a detector")
    return selected


def _is_css_state(stabilizers: npt.NDArray[np.uint8]) -> bool:
    """Test whether a complete rank-n stabilizer space is CSS in the physical basis."""
    n = len(stabilizers)
    # Let W be the stabilizer space, and W_X and W_Z the X and Z parts of its rows.  The pure-X and
    # pure-Z elements of W have dimensions n-rank(W_Z) and n-rank(W_X) and meet only in 0, so they
    # span W exactly when rank(W_X)+rank(W_Z)=n, whatever generators are used.
    ranks = [
        np.linalg.matrix_rank(galois.GF2(sector))
        for sector in (stabilizers[:, :n], stabilizers[:, n:])
    ]
    return sum(ranks) == n


def _is_integer(value: object) -> bool:
    """Test whether a value is an integer, which a bool is not."""
    return isinstance(value, numbers.Integral) and not isinstance(value, bool)


def _validate_output_qubits(qubits: tuple[int, ...], num_qubits: int) -> None:
    if (
        not qubits
        or not all(_is_integer(jj) for jj in qubits)
        or any(not 0 <= jj < num_qubits for jj in qubits)
        or len(set(qubits)) != len(qubits)
    ):
        raise ValueError("output_qubits must contain distinct in-range integer indices")


def _certify_maps(
    flags: Sequence[int],
    syndromes: Sequence[int],
    stabilizers: npt.ArrayLike,
    css_weight: bool,
    max_faults: int | None,
) -> tuple[BoundedFaultPropagationCounterexample | None, BoundedFaultPropagationStatistics]:
    """Find a violating set that passes post-selection and has the fewest faults, if one exists."""
    # A fault with no flags and no syndrome does nothing, and two faults with the same flags and
    # syndrome cancel.  Keeping one fault for each distinct nonzero (flags, syndrome) signature
    # cannot hide a violation, and each signature names its first fault.
    signatures: dict[tuple[int, int], int] = {}
    for index, signature in enumerate(zip(flags, syndromes, strict=True)):
        if any(signature):
            signatures.setdefault(signature, index)
    flag_rank = _get_binary_rank([flag for flag, _ in signatures])

    # An irreducible accepted set has at most rank + 1 faults.  If the distinct nonzero flags are
    # independent, the irreducible accepted sets of more than one fault are the pairs of faults with
    # equal nonzero flags, so the budget is at most 2.  A fault with zero flags is an irreducible
    # accepted set by itself, checked separately.
    budget = flag_rank + 1 if max_faults is None else min(max_faults, flag_rank + 1)
    if len({flag for flag, _ in signatures if flag}) == flag_rank:
        budget = min(budget, 2)

    oracle = PauliCosetSearch(stabilizers, metric="css" if css_weight else "pauli")
    counterexample, num_sets_checked = _search_irreducible_patterns(signatures, budget, oracle)
    return counterexample, BoundedFaultPropagationStatistics(flag_rank, budget, num_sets_checked)


def _search_irreducible_patterns(
    signatures: dict[tuple[int, int], int], budget: int, oracle: PauliCosetSearch
) -> tuple[BoundedFaultPropagationCounterexample | None, int]:
    """Check the irreducible accepted sets by increasing size, which finds a smallest violation.

    Return the violation, if any, and the number of sets checked.
    """
    # A fault that fires no post-selection detector is an irreducible accepted set by itself, and it
    # belongs to no larger one.
    num_checked = 0
    flagged: list[tuple[int, int, int]] = []
    for (flag, syndrome), index in signatures.items():
        if flag:
            flagged.append((flag, syndrome, index))
            continue
        num_checked += 1
        failure = _check_fault_pattern((index,), syndrome, oracle)
        if failure is not None:
            return failure, num_checked

    # If every fault alone leaves an error of weight at most one, so does every set of faults.
    if budget < 2 or all(
        oracle.get_min_weight_bound(syndrome, 1).within_max_weight for _, syndrome, _ in flagged
    ):
        return None, num_checked

    for size in range(2, budget + 1):
        for indices, syndrome in _iter_irreducible_patterns(flagged, size):
            num_checked += 1
            failure = _check_fault_pattern(indices, syndrome, oracle)
            if failure is not None:
                return failure, num_checked
    return None, num_checked


def _check_fault_pattern(
    indices: tuple[int, ...], syndrome: int, oracle: PauliCosetSearch
) -> BoundedFaultPropagationCounterexample | None:
    """Check whether a set of faults meets the bound that its size sets."""
    bound = oracle.get_min_weight_bound(syndrome, len(indices))
    if bound.within_max_weight:
        return None
    return _get_counterexample(indices, syndrome, bound, oracle.num_qubits)


def _iter_irreducible_patterns(
    faults: Sequence[tuple[int, int, int]], size: int
) -> Iterator[tuple[tuple[int, ...], int]]:
    """Yield each irreducible accepted set of a given size, with its syndrome, from the faults.

    The sets are listed by their indices into the DEM.  A prefix of independent faults in increasing
    order is closed by each later fault whose flags equal the sum of the flags of the prefix.
    """
    by_flag: dict[int, list[int]] = {}
    for position, (flag, _, _) in enumerate(faults):
        by_flag.setdefault(flag, []).append(position)

    def extend(
        indices: tuple[int, ...], start: int, flag: int, syndrome: int, basis: tuple[int, ...]
    ) -> Iterator[tuple[tuple[int, ...], int]]:
        if len(indices) == size - 1:
            closing = by_flag.get(flag, [])
            for position in closing[bisect_left(closing, start) :]:
                _, closing_syndrome, index = faults[position]
                yield indices + (index,), syndrome ^ closing_syndrome
            return
        for position in range(start, len(faults)):
            next_flag, next_syndrome, index = faults[position]
            # Reducing by the echelon basis gives zero exactly when the new flags depend on the
            # prefix, and then no irreducible accepted set extends the prefix.
            reduced = next_flag
            for row in basis:
                reduced = min(reduced, reduced ^ row)
            if reduced:
                yield from extend(
                    indices + (index,),
                    position + 1,
                    flag ^ next_flag,
                    syndrome ^ next_syndrome,
                    tuple(sorted((*basis, reduced), reverse=True)),
                )

    yield from extend((), 0, 0, 0, ())


def _get_binary_rank(columns: Sequence[int]) -> int:
    """Get the GF(2) rank of binary columns that are packed into integers."""
    pivots: dict[int, int] = {}
    for column in columns:
        while column:
            pivot = column.bit_length()
            if pivot not in pivots:
                pivots[pivot] = column
                break
            column ^= pivots[pivot]
    return len(pivots)


def _get_counterexample(
    indices: tuple[int, ...], syndrome: int, bound: MinWeightBound, num_qubits: int
) -> BoundedFaultPropagationCounterexample:
    """Describe a violating set of faults by its DEM indices and an error on the output qubits."""
    n = num_qubits
    pauli = math.op_to_string(np.array([(bound.representative >> jj) & 1 for jj in range(2 * n)]))
    return BoundedFaultPropagationCounterexample(
        indices,
        tuple((syndrome >> jj) & 1 for jj in range(n)),
        bound.lower_bound,
        str(pauli),
    )

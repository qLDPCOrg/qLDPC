# bounded fault propagation certification


def certify_bounded_fault_propagation(
    circuit: stim.Circuit,
    *,
    output_qubits: Sequence[int] | None = None,
    css_weight: bool | None = None,
    max_faults: int | None = None,
    add_flags: bool = False,
    post_select: bool | Collection[int] | Literal["flags"] = False,
) -> BoundedFaultPropagationCertificate:
    """Certify bounded fault propagation in a noisy Clifford state-preparation circuit.

    Fault propagation is bounded if, for every set of circuit faults that passes post-selection, the
    error left on the output state is equivalent to an error of weight at most the number of faults.
    Two errors are equivalent if they differ by a stabilizer of the prepared state.  The weight of
    an output error is either the physical Pauli weight (the number of qubits that the error acts
    on), or the CSS weight ``max(|x|, |z|)``, where ``x`` and ``z`` are the X and Z parts of the
    output error.

    Because Pauli error propagation through a Clifford circuit is linear and output error weight is
    subadditive, it suffices, without post-selection, to check that each fault alone leaves an error
    equivalent to one of weight at most one.  With post-selection, faults that each fire a detector
    can pass together, so the search checks every set that passes and has no smaller passing subset;
    see ``fault_propagation.md`` beside this module.  Bounded fault propagation is a sufficient
    criterion for fault-tolerant state preparation; see Definition 3 in Section 4.2 of
    `arXiv:0904.2557 <https://arxiv.org/abs/0904.2557>`_.

    With post-selection, the search can take time exponential in the number of faults per set, which
    ``max_faults`` limits.

    Args:
        circuit: Noisy Stim Clifford circuit starting in Stim's all-zero state.

    Keyword args:
        output_qubits: Distinct indices of the output qubits, at least one, in the order that the
            certificate uses for Pauli strings.  Default: all qubits that the circuit acts on and
            never measures.
        css_weight: True for CSS weight, or False for physical weight.  Default: CSS weight if the
            prepared state is a CSS state in the physical Pauli basis (meaning its stabilizer group
            is generated by pure-X and pure-Z operators), and physical weight otherwise.  A CSS code
            can prepare a non-CSS state, such as a logical Y eigenstate; pass ``css_weight=True``
            for such a state if CSS weight is appropriate.
        max_faults: The largest number of faults in a set, a positive integer.  Default: None, for
            no limit.  It does not change the result without post-selection.
        add_flags: Whether to add a flag detector for each measurement that no detector or
            observable addresses, as in ``get_state_prep_diagnostic_circuit``.  Default: False.
        post_select: The detectors to post-select on, among the circuit's detectors followed by any
            added flag detectors.  True selects all of them, False selects none, a collection of
            distinct integers selects the detectors with those indices (negative indices count back
            from the last detector), and "flags" selects exactly the added flag detectors, which
            requires ``add_flags=True``.  A set of faults passes post-selection if none of the
            selected detectors fire.  Default: False.

    Returns:
        A certificate of bounded fault propagation, which includes a counterexample if applicable.

    Raises:
        ValueError: If ``css_weight``, ``output_qubits``, ``max_faults``, or ``post_select`` has an
            invalid type or value, if the output qubits do not end in one definite stabilizer state,
            or if Stim cannot convert the circuit to a DEM.
    """
    if css_weight is not None and not isinstance(css_weight, bool):
        raise ValueError("css_weight must be a bool or None")
    if max_faults is not None:
        if not _is_integer(max_faults) or max_faults < 1:
            raise ValueError("max_faults must be a positive integer or None")
        max_faults = int(max_faults)
    if output_qubits is None:
        output_qubits = _get_unmeasured_qubits(circuit)
        if not output_qubits:
            raise ValueError("The circuit has no unmeasured qubits to use as output_qubits")
    try:
        qubits = tuple(output_qubits)
    except TypeError as error:
        raise ValueError("output_qubits must be a sequence of qubit indices") from error
    _validate_output_qubits(qubits, circuit.num_qubits)

    # Flag detectors come after the detectors that the circuit already has.
    detector_record = DetectorRecord({"prep": range(circuit.num_detectors)})
    flag_detectors = stim.Circuit()
    if add_flags:
        for measurement in get_unaddressed_measurements(circuit):
            target = stim.target_rec(measurement - circuit.num_measurements)
            flag_detectors.append("DETECTOR", [target])
    detector_record.append({"flags": range(flag_detectors.num_detectors)})
    selected = _get_post_selection_detectors(post_select, detector_record, add_flags)
    circuit = circuit + flag_detectors

    stabilizers = get_state_stabilizers(circuit, qubits)
    if len(stabilizers) != len(qubits):
        raise ValueError("Selected outputs must have a definite pure, complete stabilizer state")
    matrix = np.array([math.string_to_op(stabilizer) for stabilizer in stabilizers], dtype=np.uint8)
    resolved_css_weight = _is_css_state(matrix) if css_weight is None else css_weight
    dem, flags, syndromes = _get_fault_maps(circuit, stabilizers, qubits, selected)
    counterexample, statistics = _certify_maps(
        flags, syndromes, matrix, resolved_css_weight, max_faults
    )
    return BoundedFaultPropagationCertificate(
        counterexample is None,
        tuple(map(int, qubits)),
        tuple(map(str, stabilizers)),
        dem,
        counterexample,
        resolved_css_weight,
        max_faults,
        selected,
        statistics,
    )


@dataclass(frozen=True)
class BoundedFaultPropagationCertificate:
    """The result of certifying bounded fault propagation in a state-preparation circuit.

    Equivalence, weight, and bounded fault propagation are as defined in
    ``certify_bounded_fault_propagation``.

    Attributes:
        certified: Whether fault propagation is bounded, for sets of at most ``max_faults`` faults
            if it is not None.
        output_qubits: The output qubit indices.  Position ``i`` of every Pauli string in this
            certificate is for qubit ``output_qubits[i]``.
        target_stabilizers: Signed Stim strings that generate the stabilizer group of the prepared
            state, one per output qubit.
        detector_error_model: The circuit's detector error model, flattened and undecomposed.  Its
            detectors are the circuit's own, then any added flag detectors, then one for each target
            stabilizer, in order.
        counterexample: The counterexample if ``certified`` is False, and None otherwise.
        css_weight: Whether the certificate used CSS weight (True) or physical weight (False).
        max_faults: The largest number of faults in a set, or None for no limit.
        post_selection_detectors: The post-selection detectors, as indices among the detectors of
            ``detector_error_model``.
        statistics: Counters that describe the search.
    """

    certified: bool
    output_qubits: tuple[int, ...]
    target_stabilizers: tuple[str, ...]
    detector_error_model: stim.DetectorErrorModel
    counterexample: BoundedFaultPropagationCounterexample | None
    css_weight: bool
    max_faults: int | None
    post_selection_detectors: tuple[int, ...]
    statistics: BoundedFaultPropagationStatistics


@dataclass(frozen=True)
class BoundedFaultPropagationCounterexample:
    """A set of faults that passes post-selection and violates bounded fault propagation.

    The output error induced by these faults has no equivalent error of weight at most their number.
    No set with fewer faults violates the bound.  Equivalence and weight are as defined in
    ``certify_bounded_fault_propagation``.

    Attributes:
        fault_indices: Indices of the faults among the error instructions of the certificate's
            ``detector_error_model``, in increasing order.
        output_syndrome: The syndrome of the faults' output error: entry ``j`` is 1 if the error
            anticommutes with ``target_stabilizers[j]``.
        effective_weight_lower_bound: A lower bound on the weight of every error equivalent to the
            faults' output error, which exceeds ``fault_count``.
        output_pauli: A Pauli error with this syndrome, as a Stim string over the output qubits in
            the order of the certificate's ``output_qubits``.  It is not necessarily the lightest
            such error, or the error that the faults cause.
    """

    fault_indices: tuple[int, ...]
    output_syndrome: tuple[int, ...]
    effective_weight_lower_bound: int
    output_pauli: str

    @property
    def fault_count(self) -> int:
        """The number of faults in this counterexample."""
        return len(self.fault_indices)


@dataclass(frozen=True)
class BoundedFaultPropagationStatistics:
    """Counts that describe the search of one certification.

    Attributes:
        flag_rank: The GF(2) rank of the effects of the faults on the post-selection detectors.
        effective_budget: The largest number of faults in a set that the search checks.  It is
            ``flag_rank + 1``, limited by ``max_faults`` and by 2 if the distinct nonzero effects of
            the faults on the post-selection detectors are linearly independent.
        num_sets_checked: The number of sets that the search checked, which pass post-selection and
            have no smaller passing subset.
    """

    flag_rank: int
    effective_budget: int
    num_sets_checked: int


